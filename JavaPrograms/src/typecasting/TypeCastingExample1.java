package typecasting;

public class TypeCastingExample1 {

	public static void main(String[] args) {
		//one datatype to another datatype convertion
		//primitive, 				nonprimitive
		//implicit(widening), explicit (narrow casting)
		//int ->long			double ->int
		//int to double 
		int num =10;
		double d = num;
		System.out.println("Integer value :"+num);
		System.out.println("Double value :"+d);
		

	}

}
